export const filterByAnyNonEmptyField = (array, fieldsToCheck) => {
  return array.filter((item) =>
    fieldsToCheck.some((field) => {
      const value = item[field];
      return typeof value === "string"
        ? value.trim()
        : value !== undefined && value !== null;
    })
  );
};

